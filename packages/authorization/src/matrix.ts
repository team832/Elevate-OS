import { ROLE_KEYS } from '@elevate/shared-types';
import { grantsForRole, listPermissions } from './catalogue';

/**
 * Render the role → permission matrix as Markdown, straight from the code.
 * `docs/SECURITY_AND_PERMISSIONS.md` embeds this output and a test checks the
 * document is up to date.
 *   ✓ = all records, own = only records the user is responsible for, blank = no access
 */
export function renderPermissionMatrix(): string {
  const header = `| Permission | ${ROLE_KEYS.join(' | ')} |`;
  const divider = `|---|${ROLE_KEYS.map(() => ':-:').join('|')}|`;
  const rows = listPermissions().map((p) => {
    const cells = ROLE_KEYS.map((role) => {
      const scope = grantsForRole(role).get(p.key as never);
      return scope === 'all' ? '✓' : scope === 'own' ? 'own' : '';
    });
    return `| \`${p.key}\` | ${cells.join(' | ')} |`;
  });
  return [header, divider, ...rows].join('\n');
}

export const MATRIX_BEGIN =
  '<!-- permission-matrix:begin (generated by renderPermissionMatrix; do not edit by hand) -->';
export const MATRIX_END = '<!-- permission-matrix:end -->';

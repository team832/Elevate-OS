import { existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { migrate as migrateNodePg } from 'drizzle-orm/node-postgres/migrator';
import type { NodePgDatabase } from 'drizzle-orm/node-postgres';
import { migrate as migratePglite } from 'drizzle-orm/pglite/migrator';
import type { PgliteDatabase } from 'drizzle-orm/pglite';
import type { DatabaseHandle } from './client';

/** `packages/database/migrations` — the single, central migrations folder (D-005). */
export const MIGRATIONS_DIR = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  'migrations',
);

export function listMigrationFiles(dir: string = MIGRATIONS_DIR): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort();
}

/**
 * Apply pending SQL migrations from `migrations/` (generated by `npm run db:generate`).
 * Applied migrations are tracked in `drizzle.__drizzle_migrations`.
 * Returns the number of migration files present.
 */
export async function runMigrations(
  handle: DatabaseHandle,
  migrationsFolder: string = MIGRATIONS_DIR,
): Promise<number> {
  const files = listMigrationFiles(migrationsFolder);
  if (files.length === 0) {
    throw new Error(
      `No migrations found in ${migrationsFolder}. Run "npm run db:generate" first ` +
        '(during wave 2 module teams do not generate migrations; tests use createTestDb()).',
    );
  }
  if (handle.driver === 'pglite') {
    await migratePglite(handle.db as unknown as PgliteDatabase, { migrationsFolder });
  } else {
    await migrateNodePg(handle.db as unknown as NodePgDatabase, { migrationsFolder });
  }
  return files.length;
}
